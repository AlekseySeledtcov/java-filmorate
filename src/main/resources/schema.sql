CREATE TABLE IF NOT EXISTS film (
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(50) NOT NULL,
description VARCHAR(200) NOT NULL,
releaseDate DATE NOT NULL,
duration INTEGER NOT NULL,
rating_id INTEGER
);

-- Добавляем проверку существования индекса
DROP INDEX IF EXISTS index_id;
CREATE INDEX IF NOT EXISTS index_id ON film (id);

CREATE TABLE IF NOT EXISTS users (
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
email VARCHAR(254) NOT NULL,
login VARCHAR(32) NOT NULL,
name VARCHAR(50) NOT NULL,
birthday DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS genres (
genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
genre_name VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS genre (
film_id INTEGER REFERENCES film (id) ON DELETE CASCADE,
genre_id INTEGER REFERENCES genres (genre_id) ON DELETE NO ACTION
);


CREATE TABLE IF NOT EXISTS mpa_rating (
mpa_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
mpa_name VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS like_list (
film_id INTEGER REFERENCES film (id) ON DELETE NO ACTION,
user_id INTEGER REFERENCES users (id) ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS friends_list (
user_id INTEGER REFERENCES users (id) ON DELETE NO ACTION,
friend_id INTEGER REFERENCES users (id) ON DELETE NO ACTION
);

-- Таблица для отзывов
CREATE TABLE IF NOT EXISTS reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    is_positive BOOLEAN NOT NULL,
    user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
    film_id INTEGER REFERENCES film (id) ON DELETE CASCADE,
    useful INTEGER DEFAULT 0
);

-- Таблица для лайков/дизлайков отзывов
CREATE TABLE IF NOT EXISTS review_likes (
    review_id INTEGER REFERENCES reviews (review_id) ON DELETE CASCADE,
    user_id INTEGER REFERENCES users (id) ON DELETE CASCADE,
    is_like BOOLEAN NOT NULL,
    PRIMARY KEY (review_id, user_id)
);